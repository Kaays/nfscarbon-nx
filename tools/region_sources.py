#!/usr/bin/env python3
"""Writes the USA hook sources translated to another edition's addresses.

The hooks in app/hooks_usa.txt name addresses of the USA default.xex (sub_8XXXXXXX, 0x8XXXXXXX). For
another edition, tools/map_edition.py finds each of them in that edition's image
(app/generated/map_usa_to_<region>.txt); this script copies each hook source to app/src_<region>/ with
every address replaced by the edition's. A source with an address that was not found is left out (and
said so): its hooks stay off for that edition, the game runs its own code there.

    python3 tools/region_sources.py --region pal

Run by tools/codegen.sh for every edition but usa; app/CMakeLists.txt builds app/src_<region>/*.cpp.
"""
import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
ADDR = re.compile(r"\b(sub_|0x)(8[0-9A-Fa-f]{7})(u?)\b")


def load_map(path):
    mapping, missing = {}, set()
    for line in path.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        parts = line.split()
        usa = int(parts[0], 16)
        if parts[1] == "?":
            missing.add(usa)
        else:
            mapping[usa] = int(parts[1], 16)
    return mapping, missing


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--region", required=True)
    args = ap.parse_args()
    map_path = APP / "generated" / f"map_usa_to_{args.region}.txt"
    if not map_path.is_file():
        sys.exit(f"{map_path} not found: run tools/map_edition.py --region {args.region} first")
    mapping, missing = load_map(map_path)

    out_dir = APP / f"src_{args.region}"
    shutil.rmtree(out_dir, ignore_errors=True)
    out_dir.mkdir()
    sources = [l.strip() for l in (APP / "hooks_usa.txt").read_text().splitlines() if l.startswith("src/")]
    kept, skipped = [], []
    for rel in sources:
        text = (APP / rel).read_text()
        unknown = sorted({int(m.group(2), 16) for m in ADDR.finditer(text)
                          if int(m.group(2), 16) not in mapping and int(m.group(2), 16) % 4 == 0})
        # Addresses outside the image (masks such as 0x80000000) are not addresses: leave them.
        unknown = [a for a in unknown if 0x82000000 <= a < 0x84000000]
        if unknown:
            skipped.append((rel, unknown))
            continue

        def repl(m):
            a = int(m.group(2), 16)
            if a not in mapping:
                return m.group(0)
            return f"{m.group(1)}{mapping[a]:08X}{m.group(3)}"

        text = ADDR.sub(repl, text)
        # Local headers stay in app/src.
        text = re.sub(r'#include "(?!\.\./)([^"/]+\.h)"', r'#include "../src/\1"', text)
        header = (f"// GENERATED by tools/region_sources.py from app/{rel} for the {args.region} edition: "
                  f"USA addresses replaced by app/generated/map_usa_to_{args.region}.txt. Do not edit.\n")
        (out_dir / Path(rel).name).write_text(header + text)
        kept.append(rel)
    print(f"{args.region}: {len(kept)} hook sources translated -> app/src_{args.region}/")
    for rel, unknown in skipped:
        print(f"  left out {rel}: not found in this edition: " + ", ".join(f"0x{a:08X}" for a in unknown))


if __name__ == "__main__":
    main()
