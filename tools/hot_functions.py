#!/usr/bin/env python3
"""Writes app/function_order.ld: the functions that run most, hottest first, for the linker.

Usage: python3 tools/hot_functions.py <rex_perfil_sym.log> [more logs...] [-o app/function_order.ld]

Input: logs from tools/symbolize_profile.py (stack sampling, perfil_pilas.flag). Every name seen in a
pc, lr or stack line gets the share of samples it appeared in. Game functions (sub_XXXXXXXX) and C
functions are listed by section (.text.<name>); C++ names are skipped (the log has them demangled).

Why (nfsmw-nx docs/toolchain.md, "Function ordering"): there are tens of MB of code and the A57 has
48 KB of instruction cache and a small TLB. Hot code spread over the whole program costs a page-table
walk on far jumps. This only changes where functions are placed.
"""
import collections
import re
import sys

args = sys.argv[1:]
out = 'app/function_order.ld'
if '-o' in args:
    i = args.index('-o')
    out = args[i + 1]
    del args[i:i + 2]
if not args:
    raise SystemExit(__doc__)

weight = collections.Counter()
for path in args:
    samples = 0
    for line in open(path, encoding='utf-8', errors='ignore'):
        m = re.match(r'^\s+(\d+) muestras', line)
        if m:
            samples = int(m.group(1))
            continue
        m = re.match(r'^\s+([\d.]+)%\s+(pc|lr|pila) (.*)', line)
        if not m:
            continue
        w = float(m.group(1)) * samples / 100
        for name in set(re.findall(r'\[([^\]]+?)\+0x[0-9a-f]+\]', m.group(3))):
            weight[name] += w

# Assembly in libc/FFmpeg has no section per function: placed by object file, as nfsmw-nx does.
by_file = [
    '*libc.a:libc_a-memcpy.o(.text .text.*)',
    '*libc.a:libc_a-memmove.o(.text .text.*)',
    '*libc.a:libc_a-memset.o(.text .text.*)',
    '*libc.a:libc_a-memcmp.o(.text .text.*)',
    '*libc.a:libc_a-strcmp.o(.text .text.*)',
    '*liblibavcodec.a:fft_neon.S.obj(.text .text.*)',
    '*liblibavcodec.a:mdct_neon.S.obj(.text .text.*)',
    '*liblibavutil.a:float_dsp_neon.S.obj(.text .text.*)',
]
lines = []
seen = set()
game = 0
for name, w in weight.most_common():
    if w < 1.0:  # under one sample in total: noise
        break
    if name in ('memcpy', 'memmove', 'memset', 'memcmp', 'strcmp'):
        continue
    if re.fullmatch(r'sub_[0-9A-F]{8}', name):
        sections = [f'.text.__imp__{name}', f'.text.{name}']
        game += 1
    elif re.fullmatch(r'[A-Za-z_][A-Za-z0-9_.]*', name):
        sections = [f'.text.{name}']
    else:
        continue  # demangled C++
    for s in sections:
        if s not in seen:
            seen.add(s)
            lines.append(f'  *({s})')

with open(out, 'w') as f:
    f.write('/*\n * Hot functions grouped at the start of .text, hottest first. Generated by\n'
            ' * tools/hot_functions.py from console stack sampling. Do not edit by hand.\n */\n')
    f.write('.text : {\n')
    f.write('  /* libnx start-up code must stay at address 0 (nfsmw-nx: the NRO did not boot otherwise). */\n')
    f.write('  KEEP (*(.crt0))\n')
    for l in by_file:
        f.write(f'  {l}\n')
    f.write('\n'.join(lines) + '\n}\n')
print(f'{out}: {len(lines)} sections, {game} game functions')
